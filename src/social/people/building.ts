import type { PersonCard, SocialEffect } from '../types';

/*
 * The building's people (docs/building.md, docs/social.md): the residents behind the doors on the stairs (`door`:
 * `stairwell/building.doorKey(k, i)`), the concierge, the syndic, the attic's student, the postman, Lambert's niece.
 * Their effects' keys are read by the building's systems through `social/perks.effect`.
 */

/**
 * A resident with a door has a vote at the co-owners' meeting, and how the player stands with them sways it
 * (`building/coproSway`): these effects say so in the book and are what the sway reads.
 */
const VOTE_EFFECTS: readonly SocialEffect[] = [
  { key: 'votesWithYou', at: 'friend', text: 'Votes with you at the co-owners’ meeting' },
  { key: 'lobbies', at: 'close', text: 'Brings another resident round to your vote' },
  { key: 'votesAgainst', at: 'hostile', down: true, text: 'Votes against you at the co-owners’ meeting' },
];

function withVotes(cards: readonly PersonCard[]): readonly PersonCard[] {
  return cards.map((c) => (c.door ? { ...c, effects: [...(c.effects ?? []), ...VOTE_EFFECTS] } : c));
}

